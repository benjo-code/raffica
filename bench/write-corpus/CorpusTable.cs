using System.Globalization;
using System.Text;

namespace WriteCorpus;

/// <summary>
/// Builds <c>Docs/write-corpus.md</c>: one row per corpus entry with the round trip of this tool and Word's page counts when the owner has put
/// Word's PDFs into the entry folder. The text is deterministic (rows sorted by id, no time, no absolute path, LF line endings).
/// </summary>
internal static class CorpusTable
{
    public const string WordPdf = "word.pdf";
    public const string WordAcceptPdf = "word-accept.pdf";
    public const string WordRejectPdf = "word-reject.pdf";

    /// <summary>The cell for a value that does not exist (no PDF yet, or not applicable): an en dash.</summary>
    public const string Missing = "–";

    /// <exception cref="PdfEngineUnavailableException">A Word PDF exists but the PDF engine cannot start.</exception>
    public static async Task<string> BuildAsync(string root, CancellationToken cancellationToken = default)
    {
        var rows = CorpusRun.Evaluate(root).OrderBy(r => r.Entry.Id, StringComparer.Ordinal).ToList();
        var text = new StringBuilder();
        text.Append("# Raffica Write: compatibility corpus\n\n");
        text.Append("<!-- Generated by `write-corpus table`; do not edit by hand. -->\n\n");
        text.Append("The files of `testdata/write-corpus` and what the tool `write-corpus` finds on them. ");
        text.Append("Regenerate with `dotnet run --project bench/write-corpus -c Release -- table --root testdata/write-corpus --out Docs/write-corpus.md`.\n\n");
        text.Append("- **Opens**, **Saves**, **Identical**: the round trip of Raffica.Write.Docx (open, save, compare with the original: parts the model did not load are byte-identical, parts it loaded are equivalent). **Identical** needs both.\n");
        text.Append("- **Word pages**: the page count of `word.pdf` in the entry folder, the PDF Word makes of the file (made by the owner, see `testdata/write-corpus/README.md`). ");
        text.Append("**Accept** and **Reject** are the page counts of `word-accept.pdf` and `word-reject.pdf`, only for files with tracked changes.\n");
        text.Append($"- \"{Missing}\" means there is no such PDF in the entry folder (or the column does not apply to the file).\n");
        text.Append("- Columns for Raffica Write's own layout come with milestone 4.2.\n\n");
        text.Append("| id | source | licence | features | opens | saves | identical | Word pages | Accept | Reject |\n");
        text.Append("|---|---|---|---|---|---|---|---|---|---|\n");
        foreach (var (entry, row) in rows)
        {
            var folder = CorpusCheck.Resolve(root, entry.Path) is { } docx ? Path.GetDirectoryName(docx) : null;
            var tracked = entry.Features.Contains("tracked-changes", StringComparer.Ordinal);
            var word = await PagesAsync(folder, WordPdf, cancellationToken).ConfigureAwait(false);
            var accept = tracked ? await PagesAsync(folder, WordAcceptPdf, cancellationToken).ConfigureAwait(false) : Missing;
            var reject = tracked ? await PagesAsync(folder, WordRejectPdf, cancellationToken).ConfigureAwait(false) : Missing;
            text.Append(string.Create(
                CultureInfo.InvariantCulture,
                $"| {Cell(entry.Id)} | {Cell(entry.Source)} | {Cell(entry.License)} | {Cell(string.Join(", ", entry.Features.Order(StringComparer.Ordinal)))} | {Flag(row.Opens)} | {Flag(row.Saves)} | {Flag(row.UnloadedIdentical && row.LoadedEquivalent)} | {word} | {accept} | {reject} |\n"));
        }

        return text.ToString();
    }

    private static async Task<string> PagesAsync(string? folder, string name, CancellationToken cancellationToken)
    {
        var path = folder is null ? null : Path.Combine(folder, name);
        if (path is null || !File.Exists(path))
        {
            return Missing;
        }

        try
        {
            var facts = await PdfPageFacts.ReadAsync(path, cancellationToken).ConfigureAwait(false);
            return facts.PageCount.ToString(CultureInfo.InvariantCulture);
        }
        catch (InvalidDataException)
        {
            return "unreadable";
        }
    }

    private static string Flag(bool value) => value ? "true" : "false";

    /// <summary>A table cell: line breaks become spaces and a pipe is escaped.</summary>
    private static string Cell(string text) => text.Replace("\r", " ", StringComparison.Ordinal).Replace("\n", " ", StringComparison.Ordinal).Replace("|", "\\|", StringComparison.Ordinal);
}
