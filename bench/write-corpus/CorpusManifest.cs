using System.Text.Json;
using System.Text.Json.Serialization;

namespace WriteCorpus;

/// <summary>The compatibility corpus manifest (<c>corpus.json</c> in the corpus root): schema 1, one entry per DOCX file.</summary>
internal sealed class CorpusManifest
{
    public const int CurrentSchema = 1;
    public const string FileName = "corpus.json";

    public int Schema { get; set; } = CurrentSchema;

    public List<CorpusEntry> Files { get; set; } = [];

    public static string PathIn(string root) => Path.Combine(root, FileName);

    public static CorpusManifest Load(string root)
    {
        var path = PathIn(root);
        using var stream = File.OpenRead(path);
        return JsonSerializer.Deserialize(stream, CorpusJson.Default.CorpusManifest) ?? throw new JsonException("The manifest is empty.");
    }

    public void Save(string root)
    {
        var bytes = JsonSerializer.SerializeToUtf8Bytes(this, CorpusJson.Default.CorpusManifest);
        // LF line endings and a final newline, whatever the platform.
        var text = System.Text.Encoding.UTF8.GetString(bytes).Replace("\r\n", "\n", StringComparison.Ordinal) + "\n";
        File.WriteAllBytes(PathIn(root), new System.Text.UTF8Encoding(false).GetBytes(text));
    }
}

/// <summary>One corpus file. Paths are relative to the corpus root and use forward slashes.</summary>
internal sealed class CorpusEntry
{
    public string Id { get; set; } = "";

    public string Path { get; set; } = "";

    public string Sha256 { get; set; } = "";

    public string Source { get; set; } = "";

    /// <summary>SPDX identifier.</summary>
    public string License { get; set; } = "";

    public string LicenseFile { get; set; } = "";

    /// <summary>Date of retrieval, <c>YYYY-MM-DD</c>.</summary>
    public string Retrieved { get; set; } = "";

    public List<string> Features { get; set; } = [];
}

/// <summary>The feature tags every corpus must cover, and the licences a corpus file may carry.</summary>
internal static class CorpusFeatures
{
    public static readonly IReadOnlyList<string> Required =
    [
        "paragraphs-runs", "styles", "numbering", "sections", "tables", "merged-cells", "footnotes", "endnotes", "fields", "toc",
        "comments", "tracked-changes", "pictures-inline", "pictures-floating", "text-boxes", "headers-footers", "hyperlinks",
        "bookmarks", "content-controls", "equations", "rtl-text",
    ];

    /// <summary>SPDX ids allowed for a committed file; <c>GPL-3.0-or-later</c> is for files generated by this project.</summary>
    public static readonly IReadOnlyList<string> AllowedLicenses =
    [
        "MIT", "Apache-2.0", "BSD-2-Clause", "BSD-3-Clause", "CC0-1.0", "CC-BY-4.0", "GPL-3.0-or-later",
    ];
}

[JsonSourceGenerationOptions(PropertyNamingPolicy = JsonKnownNamingPolicy.CamelCase, WriteIndented = true, IndentSize = 2)]
[JsonSerializable(typeof(CorpusManifest))]
internal sealed partial class CorpusJson : JsonSerializerContext;
